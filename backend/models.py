"""
Data models and typed structures for ORVIX.
Ensures strong contract boundaries between sensing, prediction, impact, recovery, and audit agents.
"""

from dataclasses import dataclass, field
from datetime import datetime
from typing import List, Dict, Optional, Any


@dataclass
class TelemetryReading:
    """Simulated or live IoT sensor reading from reefer cargo bay."""
    timestamp: datetime
    temperature_c: float
    humidity_pct: float
    compressor_status: str  # "NORMAL", "DEGRADED", "OFFLINE"
    gps_lat: float
    gps_lon: float
    battery_or_fuel_pct: float
    source: str = "SIMULATED"  # REAL, SIMULATED, MANUAL


@dataclass
class WeatherCondition:
    """Atmospheric and transit corridor weather observations."""
    timestamp: datetime
    corridor_name: str
    precipitation_mm_hr: float
    flood_warning_active: bool
    road_passability_score: float  # 0.0 (blocked) to 1.0 (clear)
    forecast_rain_next_4h_mm: float
    source: str = "SIMULATED"  # REAL (if Open-Meteo API), SIMULATED fallback


@dataclass
class DisruptionEvent:
    """Structured detection from Agent A (Disruption Sensing)."""
    event_id: str
    event_type: str  # "WEATHER_FLOOD", "THERMAL_EXCURSION", "VEHICLE_BREAKDOWN", "STORAGE_UNAVAILABLE", "DEMAND_SHIFT"
    timestamp: datetime
    source: str  # REAL, SIMULATED, MANUAL
    severity: str  # "LOW", "MEDIUM", "HIGH", "CRITICAL"
    confidence_pct: float  # Data quality / confidence (0-100%)
    headline: str
    operational_relevance: str
    is_observed_fact: bool  # True if directly sensed, False if forecast/assumption


@dataclass
class RiskSignal:
    """Granular contributing factor computed by Agent B (Predictive Risk)."""
    factor_name: str
    current_value_repr: str
    threshold_repr: str
    direction: str  # "STABLE", "RISING", "CRITICAL"
    weight_pct: float
    score_contribution: float  # 0 to 100
    explanation: str


@dataclass
class PredictiveRiskAssessment:
    """Output contract from Agent B (Predictive Risk Agent)."""
    timestamp: datetime
    overall_risk_score: float  # 0.0 to 100.0 (Illustrative heuristic risk index)
    risk_tier: str  # "LOW", "MODERATE", "ELEVATED", "CRITICAL"
    direction_of_change: str  # "STABLE", "WORSENING", "ACCELERATING"
    contributing_factors: List[RiskSignal] = field(default_factory=list)
    time_to_breach_envelope_mins: Optional[float] = None
    recommended_preventive_action: str = ""
    missing_or_unreliable_signals: List[str] = field(default_factory=list)
    data_confidence_score: float = 95.0
    is_statistically_calibrated: bool = False  # Honesty flag: heuristic, not calibrated


@dataclass
class ShipmentImpact:
    """Output contract from Agent C (Shipment Impact and Scoring Agent)."""
    timestamp: datetime
    quantity_affected_kg: float
    expected_delay_minutes: int
    deadline_breached: bool
    perishability_urgency: str  # "NORMAL", "MONITORED", "URGENT", "IMMINENT_SPOILAGE"
    estimated_spoilage_cost_usd: float
    estimated_sla_penalty_usd: float
    estimated_additional_logistics_usd: float
    total_financial_exposure_usd: float
    unmet_demand_kg: float
    data_confidence_pct: float
    scoring_breakdown: Dict[str, float] = field(default_factory=dict)
    assumptions_statement: str = "All monetary estimates are illustrative scenario projections based on baseline cargo value."


@dataclass
class RecoveryAlternative:
    """Feasible or rejected operational response option generated by Agent D."""
    alt_id: str
    name: str
    description: str
    assigned_vehicle_id: str
    vehicle_capacity_kg: float
    is_vehicle_available: bool
    route_name: str
    storage_hub_id: str
    is_storage_available: bool
    estimated_delay_minutes: int
    additional_cost_usd: float
    quantity_delivered_kg: float
    deadline_feasible: bool
    is_feasible: bool
    rejection_reasons: List[str] = field(default_factory=list)
    risk_reduction_score: float = 0.0  # 0 to 100
    composite_rank_score: float = 0.0  # Multi-criteria weighted score
    is_recommended: bool = False
    recommendation_rationale: str = ""


@dataclass
class ApprovalDecision:
    """Human-in-the-loop governance record captured by Agent E."""
    decision_id: str
    timestamp: datetime
    shipment_id: str
    selected_alt_id: str
    decision_status: str  # "APPROVED", "REJECTED", "MODIFIED"
    operator_name: str
    operator_role: str
    rationale_notes: str
    modified_parameters: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AuditLogRecord:
    """Append-only audit entry stored in SQLite."""
    record_id: str
    timestamp: datetime
    shipment_id: str
    disruptions_detected: str
    risk_score: float
    risk_tier: str
    recommended_action: str
    alternatives_evaluated_count: int
    human_decision: str
    operator_id: str
    rationale_notes: str
    raw_payload_json: str
